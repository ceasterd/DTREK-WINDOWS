uint8_t dtrek_atan2_course(int y, int x)
{
    double angle;
    int course;

    if (x == 0 && y == 0) return 0;
    /* Original Atan2(y,x): 0 = up, 64 = right, 128 = down. */
    angle = atan2((double)x, (double)y);
    if (angle < 0.0) angle += 6.28318530717958647692;
    course = (int)(angle * (256.0 / 6.28318530717958647692) + 0.5);
    return (uint8_t)(course & 0xff);
}

uint8_t dtrek_course_to(int x1, int y1, int x2, int y2)
{
    return dtrek_atan2_course(y1 - y2, x2 - x1);
}

uint8_t dtrek_course_delta(uint8_t a, uint8_t b)
{
    return (uint8_t)(a - b);
}

int dtrek_isqrt(int n)
{
    unsigned int a, b, c, j, i;

    if (n <= 0) return 0;
    if (n < 4) return 1;

    a = (unsigned int)n;
    j = 0;
    while (a >>= 1) ++j;
    j >>= 1;
    a = 1u << j;
    if (!(b = (unsigned int)n - (1u << (j << 1)))) return (int)a;
    --j;

    for (i = 1u << j; i > 0; i >>= 1, --j) {
        if ((c = 1u << (j << 1)) < b) {
            if ((c += a * (2u << j)) < b) {
                a |= i;
                b = (unsigned int)n - a * a;
            }
            else if (c == b) {
                return (int)(a | i);
            }
        }
    }
    return (int)a;
}

int dtrek_ihypot(int x, int y)
{
    unsigned int max, mask, shift;

    if (x < 0) x = -x;
    if (y < 0) y = -y;
    max = (x > y) ? (unsigned int)x : (unsigned int)y;
    if (!(max & 0x7fff8000u)) return dtrek_isqrt(x * x + y * y);

    mask = 0x40000000u;
    shift = 16;
    while (!(max & mask)) {
        --shift;
        mask >>= 1;
    }
    x >>= shift;
    y >>= shift;
    return dtrek_isqrt(x * x + y * y) << shift;
}

/*
 * True when the closest point on the ray (refx,refy,dir,len) to the
 * target is within delta.  Direct port of search.c:is_vector_close_to_point.
 */
int dtrek_vector_close_to_point(
    int refx, int refy, uint8_t dir, int len,
    int targx, int targy, int delta)
{
    float ax, ay, cx, cy, d;
    int bx, by;
    float toofar;

    toofar = (float)(len + delta);
    ax = (float)(refx - targx);
    if (fabsf(ax) > toofar) return 0;
    ay = (float)(refy - targy);
    if (fabsf(ay) > toofar) return 0;

    cx = (float)dtrek_cos_table[dir];
    cy = (float)dtrek_sin_table[dir];
    if ((d = -ax * cx - ay * cy) > toofar) return 0;
    if (d <= 0.0f) {
        if ((bx = (int)fabsf(ax)) > delta) return 0;
        if ((by = (int)fabsf(ay)) > delta) return 0;
    }
    else {
        if ((bx = (int)fabsf(ax + d * cx)) > delta) return 0;
        if ((by = (int)fabsf(ay + d * cy)) > delta) return 0;
    }
    return dtrek_ihypot(bx, by) <= delta;
}
